QUESTION_MANIFESTS = [
    ROOT / "outputs" / "nysc_survey_feature_manifest.csv",
    ROOT / "outputs" / "branch_e_variable_dimension_audit" / "branch_e_all_75_variables.csv",
]


def _question_map() -> dict[str, dict]:
    result: dict[str, dict] = {}
    for path in QUESTION_MANIFESTS:
        with path.open(newline="", encoding="utf-8-sig") as handle:
            for row in csv.DictReader(handle):
                variable = row.get("variable")
                question = row.get("question_text")
                if variable and question and variable not in result:
                    result[variable] = {
                        "question_id": row.get("question_id"),
                        "question": question,
                        "type": row.get("type"),
                    }
    return result


def _summary_profiles(model_key: str, summary: dict) -> tuple[dict[str, int], dict[str, str]]:
    profiles = summary.get("profiles", {}) or summary.get("selected_candidate", {})
    sizes = profiles.get("sizes") or profiles.get("profile_sizes") or summary.get("profile_sizes") or {}
    names = profiles.get("names") or profiles.get("profile_names") or summary.get("profile_labels") or summary.get("profile_names") or {}
    sizes = {str(k): int(v) for k, v in sizes.items()}
    names = {str(k): str(v) for k, v in names.items()}
    if not sizes:
        raise ValueError(f"No final profile sizes found for {model_key}")
    return sizes, names


def _profiles(model_key: str, sizes: dict[str, int], names: dict[str, str]) -> list[dict]:
    result = []
    for profile_id in sorted(sizes, key=lambda value: int(value)):
        key = f"{model_key}_p{profile_id}"
        result.append({
            "profile_key": key,
            "profile_code": metadata_for_profile(key)["cluster_code"].removeprefix("Cluster "),
            "profile_name": names.get(profile_id, metadata_for_profile(key)["cluster_name"]),
            "historical_profile_size": sizes[profile_id],
        })
    return result


def _categorical_rows(model: dict, source: dict, profile_keys: list[str], sizes: dict[str, int], variable: str) -> dict | None:
    path = ROOT / source["distribution"]
    rows = []
    with path.open(newline="", encoding="utf-8-sig") as handle:
        for row in csv.DictReader(handle):
            if row.get(source["variable"]) == variable:
                rows.append(row)
    if not rows:
        return None
    answers: OrderedDict[str, list[dict]] = OrderedDict()
    for row in rows:
        answer = row[source["response"]]
        profile_key = f"{model['model_key']}_p{row[source['profile_id']]}"
        count = int(float(row[source["count"]]))
        percentage = float(row[source["percentage"]])
        answers.setdefault(answer, []).append({
            "profile_key": profile_key,
            "count": count,
            "denominator": sizes[str(row[source["profile_id"]])],
            "percentage": percentage,
        })
    distribution = []
    for answer, observed in answers.items():
        by_profile = {item["profile_key"]: item for item in observed}
        distribution.append({
            "answer": answer,
            "profile_values": [
                by_profile.get(key, {
                    "profile_key": key,
                    "count": 0,
                    "denominator": sizes[key.rsplit("_p", 1)[1]],
                    "percentage": 0.0,
                })
                for key in profile_keys
            ],
        })
    complete = all(
        sum(item["profile_values"][index]["count"] for item in distribution) == sizes[key.rsplit("_p", 1)[1]]
        for index, key in enumerate(profile_keys)
    )
    return {
        "kind": "categorical",
        "availability": "complete" if complete else "observed_categories_only",
        "answer_distribution": distribution,
        "note": "Percentages are within-profile percentages from the final model population.",
    }


def _numeric_rows(model: dict, source: dict, profile_keys: list[str], sizes: dict[str, int], variable: str) -> dict | None:
    assignments = source.get("assignments")
    if not assignments:
        return None
    # Final assignment outputs retain raw response values under this naming.
    column = f"{variable}__value"
    path = ROOT / assignments
    grouped: dict[str, list[float]] = {key: [] for key in profile_keys}
    with path.open(newline="", encoding="utf-8-sig") as handle:
        for row in csv.DictReader(handle):
            profile_id = row.get(source["profile_id"])
            value = row.get(column)
            if not profile_id or value in (None, "", "nan", "NaN"):
                continue
            try:
                number = float(value)
            except ValueError:
                continue
            grouped[f"{model['model_key']}_p{profile_id}"].append(number)
    if not any(grouped.values()):
        return None
    values = []
    for key in profile_keys:
        items = grouped[key]
        if items:
            q1, _, q3 = statistics.quantiles(items, n=4, method="inclusive") if len(items) >= 2 else (items[0], items[0], items[0])
            values.append({
                "profile_key": key,
                "denominator": sizes[key.rsplit("_p", 1)[1]],
                "observed": len(items),
                "missing": sizes[key.rsplit("_p", 1)[1]] - len(items),
                "mean": statistics.fmean(items),
                "median": statistics.median(items),
                "iqr": q3 - q1,
            })
        else:
            values.append({
                "profile_key": key,
                "denominator": sizes[key.rsplit("_p", 1)[1]],
                "observed": 0,
                "missing": sizes[key.rsplit("_p", 1)[1]],
            })
    return {
        "kind": "numeric_summary",
        "availability": "profile_summary",
        "numeric_values": values,
        "note": "Numeric values are shown as profile summaries; no arbitrary bins were created.",
    }


def build_library() -> dict:
    questions = _question_map()
    models: dict[str, dict] = {}
    for model_key, source in MODEL_SOURCES.items():
        summary = json.loads((ROOT / source["summary"]).read_text(encoding="utf-8"))
        sizes, names = _summary_profiles(model_key, summary)
        profile_items = _profiles(model_key, sizes, names)
        profile_keys = [item["profile_key"] for item in profile_items]
        model_meta = {"model_key": model_key, "dimension_title": MODEL_DIMENSIONS[model_key]}
        variables = []
        for variable in CLUSTER_DEFINING_REGISTRY[model_key]["variables"]:
            entry = {
                "variable": variable,
                "display_name": DISPLAY_NAMES.get(variable, variable.replace("_", " ").title()),
                "question_id": questions.get(variable, {}).get("question_id"),
                "survey_question": questions.get(variable, {}).get("question"),
                "provenance": CLUSTER_DEFINING_REGISTRY[model_key]["provenance"],
            }
            numeric = _numeric_rows(model_meta, source, profile_keys, sizes, variable)
            variable_type = questions.get(variable, {}).get("type")
            categorical = _categorical_rows(model_meta, source, profile_keys, sizes, variable)
            if variable_type == "count_or_continuous":
                evidence = numeric or categorical
            else:
                evidence = categorical or numeric
            if evidence:
                entry.update(evidence)
            else:
                entry.update({
                    "kind": "unavailable",
                    "availability": "not_recoverable_from_final_outputs",
                    "note": "No final distribution or profile summary was present for this variable.",
                })
            variables.append(entry)
        models[model_key] = {
            **model_meta,
            "source_file": source["source"],
            "profiles": profile_items,
            "cluster_forming_variables": variables,
        }
    return {
        "schema_version": "cluster_formation_evidence_library_v1",
        "description": "Deterministic evidence for the exact variables used to form each retained frozen cluster model.",
        "models": models,
    }


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    rendered = json.dumps(build_library(), ensure_ascii=False, indent=2) + "\n"
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != rendered:
            raise SystemExit("clusterFormationEvidenceLibrary.json is stale; rerun without --check")
        return
    OUT.write_text(rendered, encoding="utf-8")


if __name__ == "__main__":
    main()
